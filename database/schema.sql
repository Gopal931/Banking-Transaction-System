-- ============================================================================
-- Banking Transaction Processing System - Consolidated Database Schema
-- File: database/schema.sql
-- Database: PostgreSQL 14+
-- ============================================================================

-- Clean up existing tables in reverse dependency order
DROP TABLE IF EXISTS failed_transaction CASCADE;
DROP TABLE IF EXISTS transaction_audit CASCADE;
DROP TABLE IF EXISTS bank_transaction CASCADE;
DROP TABLE IF EXISTS account CASCADE;
DROP TABLE IF EXISTS customer CASCADE;

-- ----------------------------------------------------------------------------
-- 1. Table: customer
-- Stores core retail and corporate banking customer profile information.
-- ----------------------------------------------------------------------------
CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_customer_email UNIQUE (email),
    CONSTRAINT chk_customer_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'CLOSED'))
);

-- ----------------------------------------------------------------------------
-- 2. Table: account
-- Represents financial accounts held by customers (Checking, Savings, etc.).
-- Includes optimistic locking 'version' column to prevent concurrent lost updates.
-- ----------------------------------------------------------------------------
CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    account_number VARCHAR(20) NOT NULL,
    account_type VARCHAR(20) NOT NULL,
    balance NUMERIC(19, 2) NOT NULL DEFAULT 0.00,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_account_number UNIQUE (account_number),
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id)
        REFERENCES customer(id) ON DELETE RESTRICT,
    CONSTRAINT chk_account_type CHECK (account_type IN ('CHECKING', 'SAVINGS', 'MONEY_MARKET', 'CERTIFICATE_OF_DEPOSIT')),
    CONSTRAINT chk_account_balance CHECK (balance >= 0.00),
    CONSTRAINT chk_account_status CHECK (status IN ('ACTIVE', 'DORMANT', 'FROZEN', 'CLOSED'))
);

-- ----------------------------------------------------------------------------
-- 3. Table: bank_transaction
-- Records executed money movements: Deposits, Withdrawals, and Transfers.
-- Named bank_transaction to prevent collision with SQL reserved word 'TRANSACTION'.
-- Includes idempotency_key for safe network retries and completion timestamps.
-- ----------------------------------------------------------------------------
CREATE TABLE bank_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR(64) NOT NULL,
    idempotency_key VARCHAR(128),
    source_account_id BIGINT,
    target_account_id BIGINT,
    transaction_type VARCHAR(20) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    description VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_transaction_reference UNIQUE (transaction_reference),
    CONSTRAINT uq_transaction_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_transaction_source_account FOREIGN KEY (source_account_id)
        REFERENCES account(id) ON DELETE RESTRICT,
    CONSTRAINT fk_transaction_target_account FOREIGN KEY (target_account_id)
        REFERENCES account(id) ON DELETE RESTRICT,
    CONSTRAINT chk_transaction_type CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT chk_transaction_amount CHECK (amount > 0.00),
    CONSTRAINT chk_transaction_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REVERSED')),
    CONSTRAINT chk_transaction_party_rules CHECK (
        (transaction_type = 'DEPOSIT' AND target_account_id IS NOT NULL AND source_account_id IS NULL) OR
        (transaction_type = 'WITHDRAWAL' AND source_account_id IS NOT NULL AND target_account_id IS NULL) OR
        (transaction_type = 'TRANSFER' AND source_account_id IS NOT NULL AND target_account_id IS NOT NULL AND source_account_id <> target_account_id)
    )
);

-- ----------------------------------------------------------------------------
-- 4. Table: transaction_audit
-- Immutable ledger audit trail recording account balance before and after movements.
-- Enforces mathematical consistency invariant between balance before/after and amount.
-- ----------------------------------------------------------------------------
CREATE TABLE transaction_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    action_type VARCHAR(20) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    balance_before NUMERIC(19, 2) NOT NULL,
    balance_after NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_transaction FOREIGN KEY (transaction_id)
        REFERENCES bank_transaction(id) ON DELETE CASCADE,
    CONSTRAINT fk_audit_account FOREIGN KEY (account_id)
        REFERENCES account(id) ON DELETE RESTRICT,
    CONSTRAINT chk_audit_action_type CHECK (action_type IN ('CREDIT', 'DEBIT')),
    CONSTRAINT chk_audit_amount CHECK (amount > 0.00),
    CONSTRAINT chk_audit_balance_before CHECK (balance_before >= 0.00),
    CONSTRAINT chk_audit_balance_after CHECK (balance_after >= 0.00),
    CONSTRAINT chk_audit_math_consistency CHECK (
        (action_type = 'CREDIT' AND balance_after = balance_before + amount) OR
        (action_type = 'DEBIT'  AND balance_after = balance_before - amount)
    )
);

-- ----------------------------------------------------------------------------
-- 5. Table: failed_transaction
-- Operational dead-letter table recording rejected transactions and error reasons.
-- Includes optional transaction_id reference to bank_transaction.
-- ----------------------------------------------------------------------------
CREATE TABLE failed_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR(64) NOT NULL,
    transaction_id BIGINT,
    source_account_id BIGINT,
    target_account_id BIGINT,
    transaction_type VARCHAR(20) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    error_code VARCHAR(50) NOT NULL,
    error_message TEXT NOT NULL,
    failed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_failed_tx_bank_transaction FOREIGN KEY (transaction_id)
        REFERENCES bank_transaction(id) ON DELETE SET NULL,
    CONSTRAINT fk_failed_tx_source_account FOREIGN KEY (source_account_id)
        REFERENCES account(id) ON DELETE SET NULL,
    CONSTRAINT fk_failed_tx_target_account FOREIGN KEY (target_account_id)
        REFERENCES account(id) ON DELETE SET NULL,
    CONSTRAINT chk_failed_tx_type CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT chk_failed_tx_amount CHECK (amount > 0.00)
);

-- ----------------------------------------------------------------------------
-- Indexes for Performance, Foreign Keys, and Executive Reporting
-- ----------------------------------------------------------------------------
CREATE INDEX idx_account_customer_id ON account(customer_id);
CREATE INDEX idx_account_status ON account(status);

CREATE INDEX idx_bank_tx_source ON bank_transaction(source_account_id);
CREATE INDEX idx_bank_tx_target ON bank_transaction(target_account_id);
CREATE INDEX idx_bank_tx_created_at ON bank_transaction(created_at);
CREATE INDEX idx_bank_tx_status ON bank_transaction(status);
CREATE INDEX idx_bank_tx_daily_reconciliation ON bank_transaction(created_at DESC, transaction_type, status);

CREATE INDEX idx_audit_transaction_id ON transaction_audit(transaction_id);
CREATE INDEX idx_audit_account_id ON transaction_audit(account_id);
CREATE INDEX idx_audit_statement_lookup ON transaction_audit(account_id, created_at DESC);

CREATE INDEX idx_failed_tx_source ON failed_transaction(source_account_id);
CREATE INDEX idx_failed_tx_failed_at ON failed_transaction(failed_at);
CREATE INDEX idx_failed_tx_error_code ON failed_transaction(error_code);
CREATE INDEX idx_failed_tx_error_analysis ON failed_transaction(failed_at DESC, error_code);
